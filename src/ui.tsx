interface SpinnerProps {
  id: string
  label: string
  value: number
  min: number
  max: number
  step: number
  onChange: (v: number) => void
  /** called before a change begins (used to record an undo step) */
  onBegin?: () => void
}

const clamp = (v: number, min: number, max: number) => Math.round(Math.min(max, Math.max(min, v)) * 100) / 100

export function Spinner({ id, label, value, min, max, step, onChange, onBegin }: SpinnerProps) {
  const bump = (dir: number) => {
    onBegin?.()
    onChange(clamp(value + dir * step, min, max))
  }
  return (
    <div className="sort-group">
      <label htmlFor={id}>{label}</label>
      <div className="number-spinner">
        <button type="button" className="spinner-btn" aria-label={`Decrease ${label}`} onClick={() => bump(-1)}>
          −
        </button>
        <input
          id={id}
          className="spinner-input"
          type="number"
          min={min}
          max={max}
          step={step}
          value={value}
          inputMode="decimal"
          onFocus={onBegin}
          onChange={(e) => {
            const n = parseFloat(e.target.value)
            if (!Number.isNaN(n)) onChange(clamp(n, min, max))
          }}
        />
        <button type="button" className="spinner-btn" aria-label={`Increase ${label}`} onClick={() => bump(1)}>
          +
        </button>
      </div>
    </div>
  )
}
